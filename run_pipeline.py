"""End-to-end pipeline: ingest -> features -> model -> charts -> report.

    python run_pipeline.py                      # nba_api, 2014-15 to 2025-26 (needs stats.nba.com access)
    python run_pipeline.py --seasons 2018-19 2024-25
    python run_pipeline.py --source synthetic   # offline demo data
    python run_pipeline.py --source csv --csv data/shots.csv
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import pandas as pd

import constants as C
import features as F
import ingest
import model as M
import report
import visualize as V


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", choices=["nba_api", "sportradar", "synthetic", "csv"], default="nba_api")
    ap.add_argument("--seasons", nargs=2, default=["2014-15", "2025-26"])
    ap.add_argument("--games-per-season", type=int, default=120)
    ap.add_argument("--season-type", default="Regular Season", choices=["Regular Season", "Playoffs"])
    ap.add_argument("--timeout", type=int, default=60)
    ap.add_argument("--proxy")
    ap.add_argument("--flip-x", action="store_true", help="negate LOC_X if charts come out mirrored")
    ap.add_argument("--max-players", type=int, default=150, help="player profile pages to write (most attempts first)")
    ap.add_argument("--csv")
    ap.add_argument("--player", help="featured player for dashboard.html")
    a = ap.parse_args(argv)

    args = ["--source", a.source, "--seasons", *a.seasons, "--season-type", a.season_type,
            "--timeout", str(a.timeout), "--games-per-season", str(a.games_per_season)]
    if a.proxy:
        args += ["--proxy", a.proxy]
    if a.flip_x:
        args.append("--flip-x")
    if a.csv:
        args += ["--csv", a.csv]
    df = F.engineer(ingest.main(args))
    models, metrics, train, test = M.train_and_evaluate(df)
    xfg = M.predict_xfg(models["full"], test)
    note = ("**SYNTHETIC data** generated by `ingest.py` (fictional players, simulated shots). Numbers illustrate the pipeline and are NOT real NBA results."
            if a.source == "synthetic" else
            "Real NBA play-by-play shot data from the Sportradar NBA API v8 (a random sample of regular-season games per season)." if a.source == "sportradar"
            else f"Real NBA shot data from `nba_api` ShotChartDetail ({a.seasons[0]} to {a.seasons[1]}, {a.season_type}, all teams).")
    report.build_report(test, xfg, metrics, note)
    n, featured = V.export_all(test, models, featured=a.player, max_players=a.max_players)
    for k, v in metrics["validation"].items():
        print(f"  {k:15s} holdout ROC-AUC {v['test']['roc_auc']:.3f}  Brier {v['test']['brier']:.4f}")
    print(f"{n} player pages; dashboard for {featured}")
    print("outputs: reports/summary.md, reports/charts/index.html, reports/charts/dashboard.html")


if __name__ == "__main__":
    main()
